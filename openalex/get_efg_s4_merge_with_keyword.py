"""
Augment the merged E/F/G table (get_efg_s2_merge.py output) with one boolean
column per keyword: whether the paper's TITLE matched that keyword.

The keyword -> pid sets are produced by text_analysis/select_pid_by_keyword.py,
which writes one pickle per keyword under META_DIRE/keyword_pids/<safe_keyword>.pkl
holding [keyword, [pids...]] (whole-token match on the lemmatized title tokens when
available, else a case-insensitive substring match on the title). This script just
consumes those pid sets; whatever matching the selector used is inherited as-is.
For each keyword we add a column

    has_kw_<safe_keyword>  = True if the pid is in that keyword's pid set, else False

so a paper that was never matched (or is filtered out of the keyword scan) is
simply False.

The reference / citation / max_year filters (same as
get_efg_s3_merge_with_concept.py) are applied before the keyword columns are
added.

Input  : META_DIRE/efg_computation/gen_V3_y{year_offset}.csv   (get_efg_s2_merge.py)
         META_DIRE/keyword_pids/<safe_keyword>.pkl             (select_pid_by_keyword.py)
Output : META_DIRE/efg_computation/
           gen_V3_y{year_offset}_with_keyword_rt_{reference_threshold}_ct_{citation_threshold}_ybefore_{max_year}.csv
"""

import os
import re
import sys
import pickle

import pandas as pd

# utils.py is in this same directory; make it importable regardless of CWD.
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, BASE_DIR)
from utils import META_DIRE  # noqa: E402

meta_dire = META_DIRE
print("meta_dire", meta_dire)

load_dire = os.path.join(meta_dire, 'efg_computation')

# must match get_efg_s2_merge.py so the input filename resolves
year_offset = 5
print("year_offset", year_offset)

# filters (same as get_efg_s3_merge_with_concept.py)
reference_threshold = 1
citation_threshold = 5
# pub_year cutoff leaves room for the citation window (matches the repo convention
# pub_year < 2025 - year_offset). For year_offset == -1 (all future citations,
# no fixed window) this is 2026, i.e. all data before 2025.
max_year = 2025 - year_offset
print("reference_threshold", reference_threshold)
print("citation_threshold", citation_threshold)
print("max_year", max_year)

citation_col = f'citation_count_y{year_offset}'

# ==================================================
# keywords to flag (must already be generated by select_pid_by_keyword.py)
# ==================================================
keyword_list = ['device', 'tool', 'software', 'review', 'guideline', 'tutorial', 'new', 'novel', 'innovative',
                'theory', 'metric', 'hypothesis', 'discovery', 'dataset', 'observation', 'overview', 'method']

# normalize the same way select_pid_by_keyword.py does (lower-case, dedup, order)
seen = set()
keywords = []
for kw in keyword_list:
    kw = kw.lower().strip()
    if kw and kw not in seen:
        seen.add(kw)
        keywords.append(kw)
print("keywords:", keywords)

# same keyword -> filename mapping as select_pid_by_keyword.py
keyword_pids_dir = os.path.join(meta_dire, 'keyword_pids')

def safe_name(kw):
    return re.sub(r'[^0-9a-z]+', '_', kw).strip('_') or 'kw'

# ==================================================
# 1. load the merged E/F/G table (get_efg_s2_merge.py output)
# ==================================================
obs_path = os.path.join(load_dire, f'gen_V3_y{year_offset}.csv')
assert os.path.exists(obs_path), obs_path
df = pd.read_csv(obs_path)
print("loaded gen_V3 shape:", df.shape)

# ==================================================
# 2. citation / reference / max_year filter (matches get_efg_s3_merge_with_concept.py)
# ==================================================
n_before_filter = len(df)
df = df[
    (df['up_refer_count'] >= reference_threshold) &
    (df[citation_col] >= citation_threshold) &
    (df['pub_year'] < max_year)
].copy()
n_after_filter = len(df)
print(f"threshold filter: {n_before_filter} -> {n_after_filter} papers "
      f"(removed {n_before_filter - n_after_filter})")

# ==================================================
# 3. for each keyword, load its pid set and add a boolean column
# ==================================================
for kw in keywords:
    kw_path = os.path.join(keyword_pids_dir, f'{safe_name(kw)}.pkl')
    assert os.path.exists(kw_path), (
        f"missing keyword file for '{kw}': {kw_path} "
        f"(run text_analysis/select_pid_by_keyword.py first)"
    )
    with open(kw_path, 'rb') as f:
        saved_kw, pid_list = pickle.load(f)
    # sanity: the file should be for the keyword we expect
    assert saved_kw == kw, f"keyword mismatch in {kw_path}: file has '{saved_kw}', expected '{kw}'"

    pid_set = set(pid_list)
    col = f'has_kw_{safe_name(kw)}'
    df[col] = df['pid'].isin(pid_set)
    print(f"  '{kw}' -> column '{col}': {int(df[col].sum())} / {len(df)} papers True")

# ==================================================
# 4. save
# ==================================================
save_path = os.path.join(
    load_dire,
    f'gen_V3_y{year_offset}_with_keyword_'
    f'rt_{reference_threshold}_'
    f'ct_{citation_threshold}_'
    f'ybefore_{max_year}.csv'
)
df.to_csv(save_path, index=False)
print("output shape:", df.shape)
print("saved to:", save_path)
print("finished")
